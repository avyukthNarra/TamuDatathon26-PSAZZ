"""Regenerate docs/sai/RESULTS.md from method_states.json + results/*.json. Coordinator only.
States: alive | helps | neutral | hurts | shelved. Edit method_states.json (id: [name, owner, state, note?])."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
states = json.loads((HERE / "method_states.json").read_text())
results = {}
for p in (HERE / "results").glob("*.json"):
    d = json.loads(p.read_text())
    if isinstance(d, dict) and "points" in d and "condition_ratios" in d and not d.get("smoke"):
        results[p.stem] = d
rows = sorted((r for r in results.values()), key=lambda r: -r["points"])
final = (HERE / "FINAL.md").read_text().replace("# FINAL:", "## FINAL:") + "\n" if (HERE / "FINAL.md").is_file() else ""
out = ["# RESULTS", "", final, "Generated by `harness/leaderboard.py`. Scope `dev` = 72 validation episodes (audit set of 24 reserved).",
       "Verdicts follow MASTER_TEST_PLAN section 9. Points = 60/(1+R); differences under ~0.2 are noise.", "",
       "## Leaderboard", "", "| ID | owner | points | CI95 | stable | short | drift | shared | sec | det |", "|---|---|---|---|---|---|---|---|---|---|"]
for r in rows:
    c = r["condition_ratios"]
    ci = "-" if not r.get("ci95") else f"{r['ci95'][0]:.2f}-{r['ci95'][1]:.2f}"
    out.append(f"| {r['id']} | {r['owner']} | {r['points']:.2f} | {ci} | {c['stable']:.3f} | {c['short_history']:.3f} | "
               f"{c['drift']:.3f} | {c['shared_change']:.3f} | {r['runtime_seconds']:.0f} | {r['determinism_max_diff']} |")
out += ["", "## Method status (every catalog ID)", "", "| ID | method | owner | state | evidence |", "|---|---|---|---|---|"]
def key(i):
    digits = ''.join(ch for ch in i[1:] if ch.isdigit())
    return (i[0], int(digits), i[1 + len(digits):])
for mid in sorted(states, key=key):
    v = states[mid]
    ev = f"results/{mid}.json" if mid in results else "-"
    out.append(f"| {mid} | {v[0]} | {v[1]} | {v[2]} | {ev}{'; ' + v[3] if len(v) > 3 else ''} |")
n = {}
for v in states.values():
    n[v[2]] = n.get(v[2], 0) + 1
out += ["", "Counts: " + ", ".join(f"{k} {n[k]}" for k in sorted(n)), ""]
(HERE / "RESULTS.md").write_text("\n".join(out))
print("RESULTS.md:", n)
